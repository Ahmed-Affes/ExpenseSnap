import 'package:flutter/material.dart';

/// Categories for categorizing receipts and expenses.
enum ReceiptCategory {
  food,
  groceries,
  transport,
  utilities,
  entertainment,
  health,
  shopping,
  housing,
  other;

  /// Human-readable label for user interface.
  String get displayName {
    switch (this) {
      case ReceiptCategory.food:
        return 'Food & Dining';
      case ReceiptCategory.groceries:
        return 'Groceries';
      case ReceiptCategory.transport:
        return 'Transport';
      case ReceiptCategory.utilities:
        return 'Utilities';
      case ReceiptCategory.entertainment:
        return 'Entertainment';
      case ReceiptCategory.health:
        return 'Health';
      case ReceiptCategory.shopping:
        return 'Shopping';
      case ReceiptCategory.housing:
        return 'Housing';
      case ReceiptCategory.other:
        return 'Other';
    }
  }

  /// Appropriate Material icon representing the category.
  IconData get icon {
    switch (this) {
      case ReceiptCategory.food:
        return Icons.restaurant_outlined;
      case ReceiptCategory.groceries:
        return Icons.shopping_basket_outlined;
      case ReceiptCategory.transport:
        return Icons.directions_car_outlined;
      case ReceiptCategory.utilities:
        return Icons.bolt_outlined;
      case ReceiptCategory.entertainment:
        return Icons.movie_outlined;
      case ReceiptCategory.health:
        return Icons.medical_services_outlined;
      case ReceiptCategory.shopping:
        return Icons.shopping_bag_outlined;
      case ReceiptCategory.housing:
        return Icons.home_outlined;
      case ReceiptCategory.other:
        return Icons.receipt_long_outlined;
    }
  }

  /// Safe conversion from string (from Gemini API / n8n backend).
  static ReceiptCategory fromString(String? value) {
    if (value == null || value.trim().isEmpty) {
      return ReceiptCategory.other;
    }

    final normalized = value.trim().toLowerCase();

    // Direct match against enum name or display name
    for (final category in ReceiptCategory.values) {
      if (category.name.toLowerCase() == normalized ||
          category.displayName.toLowerCase() == normalized) {
        return category;
      }
    }

    // Common synonym fallbacks
    if (normalized.contains('food') ||
        normalized.contains('restaurant') ||
        normalized.contains('cafe')) {
      return ReceiptCategory.food;
    }
    if (normalized.contains('grocer') ||
        normalized.contains('supermarket') ||
        normalized.contains('market')) {
      return ReceiptCategory.groceries;
    }
    if (normalized.contains('transport') ||
        normalized.contains('taxi') ||
        normalized.contains('fuel') ||
        normalized.contains('gas')) {
      return ReceiptCategory.transport;
    }
    if (normalized.contains('utilit') ||
        normalized.contains('electric') ||
        normalized.contains('water') ||
        normalized.contains('bill')) {
      return ReceiptCategory.utilities;
    }
    if (normalized.contains('health') ||
        normalized.contains('pharm') ||
        normalized.contains('medic')) {
      return ReceiptCategory.health;
    }
    if (normalized.contains('shop') || normalized.contains('store')) {
      return ReceiptCategory.shopping;
    }

    return ReceiptCategory.other;
  }
}

/// Data model representing a receipt.
///
/// Contains extraction results from Gemini (Workflow A),
/// user edits (Review Screen), and stored records (Workflow B & C).
class Receipt {
  /// Unique identifier generated by n8n backend (null before saving).
  final String? id;

  /// Timestamp when the receipt was saved (null before saving).
  final DateTime? createdAt;

  /// Merchant or store name.
  final String merchant;

  /// Purchase date in 'YYYY-MM-DD' format.
  final String date;

  /// Total monetary expense amount.
  final double amount;

  /// Currency code (defaults to 'TND').
  final String currency;

  /// Categorization of the expense.
  final ReceiptCategory category;

  /// Extraction confidence from Gemini (0.0 to 1.0, null if unavailable).
  final double? confidence;

  const Receipt({
    this.id,
    this.createdAt,
    required this.merchant,
    required this.date,
    required this.amount,
    this.currency = 'TND',
    this.category = ReceiptCategory.other,
    this.confidence,
  });

  /// Parse receipt from backend JSON map.
  factory Receipt.fromJson(Map<String, dynamic> json) {
    // Parse nullable createdAt
    DateTime? parsedCreatedAt;
    if (json['createdAt'] != null) {
      parsedCreatedAt = DateTime.tryParse(json['createdAt'].toString());
    }

    // Parse amount safely from num or String
    double parsedAmount = 0.0;
    final rawAmount = json['amount'];
    if (rawAmount is num) {
      parsedAmount = rawAmount.toDouble();
    } else if (rawAmount != null) {
      parsedAmount = double.tryParse(rawAmount.toString()) ?? 0.0;
    }

    // Parse confidence safely from num or String
    double? parsedConfidence;
    final rawConfidence = json['confidence'];
    if (rawConfidence is num) {
      parsedConfidence = rawConfidence.toDouble();
    } else if (rawConfidence != null) {
      parsedConfidence = double.tryParse(rawConfidence.toString());
    }

    return Receipt(
      id: json['id']?.toString(),
      createdAt: parsedCreatedAt,
      merchant: json['merchant']?.toString() ?? '',
      date: json['date']?.toString() ?? '',
      amount: parsedAmount,
      currency: json['currency']?.toString() ?? 'TND',
      category: ReceiptCategory.fromString(json['category']?.toString()),
      confidence: parsedConfidence,
    );
  }

  /// Convert receipt to JSON map for sending to n8n (Workflow B).
  Map<String, dynamic> toJson() {
    final map = <String, dynamic>{
      'merchant': merchant,
      'date': date,
      'amount': amount,
      'currency': currency,
      'category': category.name,
    };

    if (id != null) {
      map['id'] = id;
    }
    if (createdAt != null) {
      map['createdAt'] = createdAt!.toIso8601String();
    }
    if (confidence != null) {
      map['confidence'] = confidence;
    }

    return map;
  }

  /// Creates a copy of this receipt with modified fields.
  Receipt copyWith({
    String? id,
    DateTime? createdAt,
    String? merchant,
    String? date,
    double? amount,
    String? currency,
    ReceiptCategory? category,
    double? confidence,
  }) {
    return Receipt(
      id: id ?? this.id,
      createdAt: createdAt ?? this.createdAt,
      merchant: merchant ?? this.merchant,
      date: date ?? this.date,
      amount: amount ?? this.amount,
      currency: currency ?? this.currency,
      category: category ?? this.category,
      confidence: confidence ?? this.confidence,
    );
  }
}

/// Container for history items and total sum returned by Workflow C.
class ReceiptList {
  /// List of receipts in the retrieved period.
  final List<Receipt> items;

  /// Sum of all receipt amounts in the period.
  final double total;

  const ReceiptList({required this.items, required this.total});

  /// Parse from n8n response: `{"items": [...], "total": 123.45}`.
  factory ReceiptList.fromJson(Map<String, dynamic> json) {
    final rawItems = json['items'];
    final itemsList = <Receipt>[];

    if (rawItems is List) {
      for (final item in rawItems) {
        if (item is Map<String, dynamic>) {
          itemsList.add(Receipt.fromJson(item));
        }
      }
    }

    // Safely parse total
    final rawTotal = json['total'];
    double computedTotal = 0.0;
    if (rawTotal is num) {
      computedTotal = rawTotal.toDouble();
    } else if (rawTotal != null) {
      computedTotal = double.tryParse(rawTotal.toString()) ?? 0.0;
    } else {
      // Fallback: calculate total directly from items if not provided
      computedTotal = itemsList.fold(0.0, (sum, r) => sum + r.amount);
    }

    return ReceiptList(items: itemsList, total: computedTotal);
  }

  /// Convert to JSON map
  Map<String, dynamic> toJson() {
    return {'items': items.map((r) => r.toJson()).toList(), 'total': total};
  }
}
